//! The play record: everything needed to re-evaluate a play.

use std::ops::Range;

use bms_model::{ChartIdentity, Speed, TimeUs};
use eval::{DeviceProfile, InputStart, PhysicalInputEvent, SourceProfile};
use rules::{GaugeValue, RulePreset};

use sha2::{Digest, Sha256};

/// Whether the app that recorded the play was a production or a development
/// build.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BuildProvenance {
    /// A production build.
    Production,
    /// A build with the `dev-tools` feature.
    Development,
}

/// The versions of the parts that produced the record. The format version
/// is the header's and the loader version is
/// [`ChartIdentity::loader_version`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Versions {
    /// Version of the evaluator rules.
    pub evaluator: u32,
    /// Version of the app.
    pub app: String,
    /// Which kind of build recorded the play.
    pub provenance: BuildProvenance,
}

/// The chart a play used.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ChartRecord {
    /// The file hashes, resolved hash, loader version and `#RANDOM` results.
    pub identity: ChartIdentity,
    /// The seed `#RANDOM` was resolved with.
    pub random_seed: u64,
    /// The transform applied to the resolved chart before evaluation.
    pub transform: TransformRecord,
}

/// A chart transformation (design.md "Extension Boundaries"): which one,
/// and the version of its rules, so a replay transforms the chart the same
/// way.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct TransformRecord {
    /// The transform's id.
    pub id: String,
    /// The version of its rules.
    pub version: u32,
}

/// Which transform was applied: its id and the version of its rules, as
/// the code names it; [`record`](Self::record) gives the form the input log
/// stores.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct TransformId {
    /// The transform's id.
    pub id: &'static str,
    /// The version of its rules; a change of output bumps it.
    pub version: u32,
}

impl TransformId {
    /// The form the input log stores.
    #[must_use]
    pub fn record(self) -> TransformRecord {
        TransformRecord {
            id: self.id.to_owned(),
            version: self.version,
        }
    }

    /// Whether `record` names this transform at this version.
    #[must_use]
    pub fn is(self, record: &TransformRecord) -> bool {
        record.id == self.id && record.version == self.version
    }
}

/// The pass-through transform, which returns the chart unchanged: the only
/// transform verification knows (design.md "Determinism").
pub const PASSTHROUGH: TransformId = TransformId {
    id: "passthrough",
    version: 1,
};

/// The preset a play was evaluated under.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PresetRecord {
    /// The preset's id.
    pub id: String,
    /// SHA-256 of [`canonical_bytes`](Self::canonical_bytes).
    pub sha256: [u8; 32],
    /// A copy of the preset's canonical bytes.
    pub canonical_bytes: Vec<u8>,
}

impl PresetRecord {
    /// The record of `preset`.
    #[must_use]
    pub fn of(preset: &RulePreset) -> Self {
        let canonical_bytes = preset.canonical_bytes();
        Self {
            id: preset.id.clone(),
            sha256: Sha256::digest(&canonical_bytes).into(),
            canonical_bytes,
        }
    }
}

/// What kind of device a source is.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DeviceKind {
    /// A keyboard.
    Keyboard,
    /// A HID game controller.
    Controller,
}

/// How a source's input was received.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ReceiveMethod {
    /// Windows Raw Input.
    RawInput,
    /// Generated by the app: scripted input or autoplay.
    Scripted,
}

/// One source of the play.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SourceRecord {
    /// What kind of device it is.
    pub kind: DeviceKind,
    /// How its input was received.
    pub receive: ReceiveMethod,
    /// Its input offset and bindings.
    pub profile: SourceProfile,
    /// How many values its absolute axes reported outside the range their
    /// conversion uses (the revolution `device.toml` sets, else the
    /// declared range): that range is wrong, so their conversion may be
    /// off. The
    /// values are recorded as reported, and re-evaluation converts them
    /// as live play did.
    pub axis_out_of_range: u64,
}

/// When the input thread woke during the play, which bounds when its
/// input was stamped and how often the watermark moved.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum WakePolicy {
    /// Woken by input, at most once per `input_gap_us`, and by a heartbeat
    /// at most `heartbeat_us` after each publication; one batch read at
    /// most `drain_cut` messages before it published.
    Input {
        /// The heartbeat's bound, in µs.
        heartbeat_us: u32,
        /// The shortest time between input wakes, in µs.
        input_gap_us: u32,
        /// The most messages one batch read.
        drain_cut: u32,
    },
    /// Woken by a timer only, every `heartbeat_us` (input from no device).
    Timer {
        /// The timer's period, in µs.
        heartbeat_us: u32,
    },
}

/// The devices and offsets a play was evaluated with.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DeviceRecord {
    /// The participating sources, indexed by [`eval::SourceId`].
    pub sources: Vec<SourceRecord>,
    /// The audio latency offset.
    pub audio_offset: TimeUs,
    /// The display latency offset.
    pub display_offset: TimeUs,
    /// The input thread's wake policy.
    pub wake: WakePolicy,
}

impl DeviceRecord {
    /// The profile the evaluator reads.
    #[must_use]
    pub fn profile(&self) -> DeviceProfile {
        DeviceProfile {
            sources: self.sources.iter().map(|s| s.profile.clone()).collect(),
        }
    }
}

/// Which part of the chart was played.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum PlayType {
    /// The whole chart.
    Full,
    /// A practice round from a position in the chart, played once.
    MidChartStart(Practice),
    /// A practice round of a section played repeatedly: one round.
    SectionRepeat(Practice),
}

impl PlayType {
    /// The practice conditions; `None` for a full play.
    #[must_use]
    pub const fn practice(&self) -> Option<&Practice> {
        match self {
            Self::Full => None,
            Self::MidChartStart(p) | Self::SectionRepeat(p) => Some(p),
        }
    }
}

/// The evaluation conditions of a practice round (design.md "Practice
/// Records"): the section evaluated, as [`eval::Section`] takes it, the
/// round's number, and the initial gauges by gauge ID.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Practice {
    /// The section's first time, in the record's (real) time, as evaluated.
    pub start: TimeUs,
    /// The time just past the section.
    pub end: TimeUs,
    /// How long before `start` the lead-in begins.
    pub lead_in: TimeUs,
    /// The play's number in its session, from 1: each round is one.
    pub attempt: u32,
    /// Each gauge's value at the start, by the ID of the preset's gauge it
    /// started, in the preset's order; IDs are unique.
    pub initial_gauges: Vec<InitialGauge>,
}

/// One gauge's value at the start of a practice round.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct InitialGauge {
    /// The gauge's ID in the preset.
    pub id: String,
    /// Its value.
    pub value: GaugeValue,
}

/// A device that arrived during play. It does not take part in the play.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Arrival {
    /// When it arrived.
    pub at: TimeUs,
    /// What kind of device it is.
    pub kind: DeviceKind,
}

/// How the play ended.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EndStatus {
    /// Evaluation completed.
    PlayedToEnd,
    /// The play was aborted; it is evaluated up to the finalized watermark.
    EndedMidway,
    /// The attempt ended before its transport committed (design.md "Play
    /// Lifecycle", ending without a played attempt): a capture with no
    /// played attempt, no winning opening, no finalized watermark and no
    /// score, whose openings are all in [`PlayRecord::history`].
    CancelledBeforePlayback,
}

impl EndStatus {
    /// Whether there is a played attempt: a winning opening whose input is
    /// evaluated up to the finalized watermark.
    #[must_use]
    pub const fn played(self) -> bool {
        !matches!(self, Self::CancelledBeforePlayback)
    }
}

/// Why the recorded input may be missing events. Several reasons can hold.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Incomplete {
    /// An input queue or the log reached its capacity.
    pub overflow: bool,
    /// A device beyond the source limit did not take part.
    pub source_limit: bool,
    /// The system suspended during play, so the clock jumped.
    pub suspend: bool,
    /// The input thread failed, so recording did not close normally: what
    /// reached the queues after the play's last step is not in the record.
    pub input_failed: bool,
}

impl Incomplete {
    /// Whether any reason holds.
    #[must_use]
    pub const fn any(self) -> bool {
        self.overflow || self.source_limit || self.suspend || self.input_failed
    }
}

/// How the play ended and what of it was evaluated.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Status {
    /// How the play ended.
    pub end: EndStatus,
    /// The watermark the evaluator had finalized at the end. A capture
    /// cancelled before playback has none: it is not written, and reads
    /// back as `TimeUs(0)`.
    pub finalized: TimeUs,
    /// Why the input may be incomplete.
    pub incomplete: Incomplete,
}

/// Why a READY opening was cancelled (design.md "Play Lifecycle", the
/// start gate).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CancelReason {
    /// START or SELECT was held before its transport committed; the
    /// attempt then waited for their release.
    Held,
    /// The quit key.
    Quit,
    /// The retry key.
    Retry,
    /// The window was closed.
    Close,
    /// Focus was lost.
    FocusLost,
    /// A failure: an input thread that ended, an audio or screen failure,
    /// or a failed restore plan.
    Failed,
    /// The history or the input capacity ran out: the capture is sealed
    /// and incomplete.
    Exhausted,
}

/// One READY opening the start gate cancelled: audit history, never input
/// of the score (design.md "Input Log Format", cancelled openings).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CancelledOpening {
    /// The controls held when it opened, and its opening time on its own
    /// timeline.
    pub start: InputStart,
    /// Where its time 0 lies on the timeline of the attempt's last
    /// opening (the winning one, or for a capture cancelled before
    /// playback the last cancelled one, whose offset is 0). Receive times
    /// are never rewritten: its events keep its own timeline, and this
    /// relates the two.
    pub origin: TimeUs,
    /// When it closed, on its own timeline.
    pub closed: TimeUs,
    /// Its events' range in [`ReadyHistory::events`].
    pub events: Range<u32>,
    /// Its arrivals' range in [`ReadyHistory::arrivals`].
    pub arrivals: Range<u32>,
    /// Why it was cancelled.
    pub reason: CancelReason,
}

/// The READY openings of the attempt the start gate cancelled, in order,
/// with their raw events and arrivals in two shared arenas that the
/// openings' ranges tile in order. Every opening names its sources in the
/// record's one source table ([`DeviceRecord::sources`]). Empty for an
/// attempt whose first READY played.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ReadyHistory {
    /// The cancelled openings, at most [`MAX_CANCELLED_OPENINGS`](crate::MAX_CANCELLED_OPENINGS).
    pub openings: Vec<CancelledOpening>,
    /// Their events, at most [`MAX_CANCELLED_EVENTS`](crate::MAX_CANCELLED_EVENTS).
    pub events: Vec<PhysicalInputEvent>,
    /// Their arrivals, at most
    /// [`MAX_OPENING_ARRIVALS`](crate::MAX_OPENING_ARRIVALS) each.
    pub arrivals: Vec<Arrival>,
}

/// A recorded play: the inputs that reproduce its evaluation.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PlayRecord {
    /// The versions that produced it.
    pub versions: Versions,
    /// The chart.
    pub chart: ChartRecord,
    /// The preset.
    pub preset: PresetRecord,
    /// The id of the session policy.
    pub session_policy: String,
    /// The devices and offsets.
    pub devices: DeviceRecord,
    /// Which part of the chart was played.
    pub play_type: PlayType,
    /// The practice speed the chart was loaded at: its times, and so the
    /// input's, are real times at it.
    pub speed: Speed,
    /// The controls held when the winning opening's recording opened. A
    /// capture cancelled before playback has no winning opening: this is
    /// `InputStart::default()` and is not written.
    pub start: InputStart,
    /// The play adjustments the winning opening started with: present
    /// exactly when the record has a played attempt, and written only
    /// then.
    pub start_tuning: Option<StartTuning>,
    /// The winning opening's physical input events in stream order, the
    /// only input evaluated; empty for a capture cancelled before playback.
    pub events: Vec<PhysicalInputEvent>,
    /// Devices that arrived during the winning opening; empty for a
    /// capture cancelled before playback.
    pub arrivals: Vec<Arrival>,
    /// How the play ended.
    pub status: Status,
    /// The READY openings cancelled before the winning one, or every
    /// opening of a capture cancelled before playback.
    pub history: ReadyHistory,
}

impl PlayRecord {
    /// Whether the record has a played attempt ([`EndStatus::played`]).
    #[must_use]
    pub const fn played(&self) -> bool {
        self.status.end.played()
    }
}

/// How the hi-speed multiplier followed the settings (design.md "Play
/// Adjustments").
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum TuningMode {
    /// A saved multiplier, edited directly.
    Classic,
    /// The multiplier solved from the target green number.
    #[default]
    Floating,
}

/// The chart tempo a Floating preparation solves from.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum TuningReference {
    /// The chart's initial tempo.
    #[default]
    Start,
    /// The highest tempo.
    Maximum,
    /// The tempo weighted by its notes.
    Main,
    /// The lowest tempo.
    Minimum,
}

/// Which lane cover.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TuningCover {
    /// SUDDEN+.
    Sudden,
    /// LIFT.
    Lift,
    /// HIDDEN+.
    Hidden,
}

/// One lane cover: its configured amount, kept while it is off, and its
/// switch.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct CoverRecord {
    /// ‰, 0 to [`MAX_COVER`].
    pub amount: u16,
    /// Whether it is on.
    pub on: bool,
}

/// The exact multiplier `H`, a ratio in lowest terms within
/// [`HISPEED_MIN`] and [`HISPEED_MAX`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct HiSpeedRatio {
    /// The numerator.
    pub num: u64,
    /// The denominator, never 0.
    pub den: u64,
}

/// The play adjustments' state a played attempt's winning opening started
/// with (design.md "Input Log Format", the starting tuning): presentation
/// only, which the evaluator never reads. Its default is the settings'
/// defaults with no multiplier solved and no cover target.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct StartTuning {
    /// Classic or Floating.
    pub mode: TuningMode,
    /// What a Floating preparation solves from.
    pub reference: TuningReference,
    /// Classic's saved multiplier in hundredths, in [`CLASSIC_HISPEED_X100`].
    pub classic_hispeed_x100: u32,
    /// Classic's step in hundredths, in [`CLASSIC_STEP_X100`].
    pub classic_step_x100: u32,
    /// Floating's step in hundredths, in [`FLOATING_STEP_X100`] and a
    /// multiple of 5.
    pub floating_step_x100: u32,
    /// The target green number, in [`GREEN_TARGET`].
    pub green_target: u32,
    /// SUDDEN+.
    pub sudden: CoverRecord,
    /// LIFT.
    pub lift: CoverRecord,
    /// HIDDEN+.
    pub hidden: CoverRecord,
    /// The cover the controls adjusted; `None` with no active cover.
    pub target: Option<TuningCover>,
    /// The multiplier `H` in effect; `None` when none was solved (a play
    /// without the adjustment controls, or a chart with no reference
    /// tempo).
    pub hispeed: Option<HiSpeedRatio>,
}

impl Default for StartTuning {
    fn default() -> Self {
        Self {
            mode: TuningMode::Floating,
            reference: TuningReference::Start,
            classic_hispeed_x100: 100,
            classic_step_x100: 25,
            floating_step_x100: 50,
            green_target: 300,
            sudden: CoverRecord::default(),
            lift: CoverRecord::default(),
            hidden: CoverRecord::default(),
            target: None,
            hispeed: None,
        }
    }
}

/// Classic's saved multiplier, in hundredths: 0.01 to 20.
pub const CLASSIC_HISPEED_X100: std::ops::RangeInclusive<u32> = 1..=2000;
/// Classic's step, in hundredths: 0.01 to 1.00.
pub const CLASSIC_STEP_X100: std::ops::RangeInclusive<u32> = 1..=100;
/// Floating's step, in hundredths: 0.05 to 1.00, in multiples of 5.
pub const FLOATING_STEP_X100: std::ops::RangeInclusive<u32> = 5..=100;
/// The target green number.
pub const GREEN_TARGET: std::ops::RangeInclusive<u32> = 1..=6000;
/// The largest cover amount, ‰.
pub const MAX_COVER: u16 = 1000;
/// The smallest multiplier, 1/100.
pub const HISPEED_MIN: HiSpeedRatio = HiSpeedRatio { num: 1, den: 100 };
/// The largest multiplier, 20.
pub const HISPEED_MAX: HiSpeedRatio = HiSpeedRatio { num: 20, den: 1 };

impl HiSpeedRatio {
    /// Whether it is in lowest terms, its denominator positive, and within
    /// [`HISPEED_MIN`] and [`HISPEED_MAX`].
    #[must_use]
    pub fn is_valid(self) -> bool {
        let Self { num, den } = self;
        let (n, d) = (u128::from(num), u128::from(den));
        den != 0
            && gcd(num, den) == 1
            && n * u128::from(HISPEED_MIN.den) >= u128::from(HISPEED_MIN.num) * d
            && n * u128::from(HISPEED_MAX.den) <= u128::from(HISPEED_MAX.num) * d
    }
}

const fn gcd(mut a: u64, mut b: u64) -> u64 {
    while b != 0 {
        let t = a % b;
        a = b;
        b = t;
    }
    a
}

impl StartTuning {
    /// The first field outside its range, by name; `None` when every
    /// field is valid.
    #[must_use]
    pub fn invalid(&self) -> Option<&'static str> {
        let covers = [self.sudden, self.lift, self.hidden];
        if !CLASSIC_HISPEED_X100.contains(&self.classic_hispeed_x100) {
            Some("classic hi-speed")
        } else if !CLASSIC_STEP_X100.contains(&self.classic_step_x100) {
            Some("classic step")
        } else if !FLOATING_STEP_X100.contains(&self.floating_step_x100)
            || !self.floating_step_x100.is_multiple_of(5)
        {
            Some("floating step")
        } else if !GREEN_TARGET.contains(&self.green_target) {
            Some("green target")
        } else if covers.iter().any(|c| c.amount > MAX_COVER) {
            Some("cover amount")
        } else if self.hispeed.is_some_and(|h| !h.is_valid()) {
            Some("hi-speed")
        } else {
            None
        }
    }
}
